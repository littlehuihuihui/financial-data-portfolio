def esc_js(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def find_toolbox_span(text: str) -> tuple[int, int] | None:
    m = re.search(r"window\.ANALYSIS_TOOLBOX\s*=\s*\{", text)
    if not m:
        return None
    i = text.find("{", m.end() - 1)
    depth = 0
    for j in range(i, len(text)):
        c = text[j]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return m.start(), j + 1
    return None


def iter_method_spans(toolbox: str) -> list[tuple[str, int, int]]:
    """Return (id, start, end) relative to toolbox string."""
    spans = []
    # Match both multiline and same-line id/title
    for m in re.finditer(r'\{\s*id:\s*"([^"]+)"\s*,\s*title:\s*"([^"]+)"', toolbox):
        start = m.start()
        # find matching closing brace for this object
        depth = 0
        end = None
        for j in range(start, len(toolbox)):
            if toolbox[j] == "{":
                depth += 1
            elif toolbox[j] == "}":
                depth -= 1
                if depth == 0:
                    end = j + 1
                    break
        if end:
            spans.append((m.group(1), start, end))
    return spans


def set_or_replace_field(block: str, field: str, value: str) -> str:
    pat = re.compile(rf'({field}:\s*")((?:\\.|[^"\\])*)(")', re.S)
    if pat.search(block):
        return pat.sub(lambda m: m.group(1) + esc_js(value) + m.group(3), block, count=1)
    # insert before chartType or data or closing
    insert = f'\n        {field}: "{esc_js(value)}",'
    for anchor in ("chartType:", "data:", "portfolio:", "businessQuestion:"):
        idx = block.find(anchor)
        if idx > 0:
            return block[:idx] + insert.strip() + "\n        " + block[idx:]
    # before last }
    ridx = block.rfind("}")
    return block[:ridx] + "," + insert + "\n      " + block[ridx:]


def apply_enrichment(block: str, fields: dict) -> str:
    out = block
    for f, v in fields.items():
        out = set_or_replace_field(out, f, v)
    # mirrors
    if "definition" in fields:
        out = set_or_replace_field(out, "what", fields["definition"])
    if "applicable" in fields:
        out = set_or_replace_field(out, "when", fields["applicable"])
    if "steps" in fields:
        out = set_or_replace_field(out, "how", fields["steps"])
    return out


def field_lens(block: str) -> dict:
    out = {}
    for f in CORE_FIELDS:
        m = re.search(rf'{f}:\s*"((?:\\.|[^"\\])*)"', block, re.S)
        out[f] = len(m.group(1)) if m else 0
    return out


