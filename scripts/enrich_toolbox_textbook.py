def enrich_file(industry: str, path: Path) -> tuple[int, list[str]]:
    text = path.read_text(encoding="utf-8")
    span = find_toolbox_span(text)
    if not span:
        raise SystemExit(f"ANALYSIS_TOOLBOX not found in {path}")
    a, b = span
    toolbox = text[a:b]
    enrich = ENRICHMENTS[industry]
    spans = iter_method_spans(toolbox)
    # apply from end to start to keep offsets
    changed = 0
    notes = []
    for mid, s, e in sorted(spans, key=lambda x: -x[1]):
        if mid not in enrich:
            continue
        old = toolbox[s:e]
        new = apply_enrichment(old, enrich[mid])
        if new != old:
            toolbox = toolbox[:s] + new + toolbox[e:]
            changed += 1
            notes.append(mid)
    text = text[:a] + toolbox + text[b:]
    path.write_text(text, encoding="utf-8")
    return changed, notes


def audit(path: Path) -> None:
    text = path.read_text(encoding="utf-8")
    span = find_toolbox_span(text)
    toolbox = text[span[0] : span[1]]
    print(f"\n== {path.name} ==")
    for mid, s, e in iter_method_spans(toolbox):
        lens = field_lens(toolbox[s:e])
        weak = [f for f, L in lens.items() if L < int(TARGETS[f] * 0.7)]
        flag = "WEAK" if weak else "ok"
        if flag == "WEAK" or mid == "pareto":
            print(f"  [{flag}] {mid:22} {weak if weak else lens}")


